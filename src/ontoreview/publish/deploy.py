"""Deployment kit written into every documentation website: a how-to (DEPLOY.md), Docker (nginx
image + compose), a complete nginx server block, a local preview script, and a GitHub Actions
workflow that publishes the folder to GitHub Pages on every push.

The kit is static text; nothing here contacts a server. The app's "Deploy to GitHub Pages" action
(``ontoreview.publish.github``) pushes a website folder that contains it.
"""

from __future__ import annotations

from pathlib import Path

PAGES_WORKFLOW = ".github/workflows/pages.yml"
DEPLOY_FILES = ("DEPLOY.md", "Dockerfile", "docker-compose.yml", ".dockerignore", "deploy/nginx.conf",
                "deploy/serve.sh", "deploy/serve.bat", PAGES_WORKFLOW)


def pages_workflow(branch: str = "main") -> str:
    """GitHub Pages from this folder as is (no build step: the docs are already built)."""
    return f"""# Generated by OntoReview: publishes this documentation folder to GitHub Pages.
# One-time setup: repository Settings > Pages > Build and deployment > Source: "GitHub Actions".
name: Deploy documentation to GitHub Pages

on:
  push:
    branches: [{branch}]
  workflow_dispatch:

permissions:
  contents: read
  pages: write
  id-token: write

concurrency:
  group: pages
  cancel-in-progress: false

jobs:
  deploy:
    environment:
      name: github-pages
      url: ${{{{ steps.deployment.outputs.page_url }}}}
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: actions/configure-pages@v5
      - uses: actions/upload-pages-artifact@v3
        with:
          path: .
      - id: deployment
        uses: actions/deploy-pages@v4
"""


def nginx_server(files: list[dict]) -> str:
    """A complete nginx server block (conf.d), with content negotiation on the folder root."""
    entries = "\n".join(f'    "~{f["media"].replace("+", "[+]")}" /{f["file"]};' for f in files)
    return f"""# Generated by OntoReview: serves this documentation folder (Docker image or any nginx).
# Without Docker: copy the folder to /usr/share/nginx/html (or change root below) and put this
# file in /etc/nginx/conf.d/. Asking for the site root with an RDF Accept header returns the
# ontology in that format (content negotiation); browsers get the HTML.
map $http_accept $ontoreview_target {{
    default "";
{entries}
}}

server {{
    listen 80;
    server_name _;
    root /usr/share/nginx/html;
    index index.html;
    charset utf-8;
    absolute_redirect off;      # relative redirects: correct behind proxies and on any port

    types {{
        text/html html;
        text/css css;
        application/javascript js;
        application/json json;
        image/svg+xml svg;
        image/png png;
        text/plain txt;
        text/markdown md;
        text/turtle ttl;
        application/rdf+xml owl rdf;
        application/ld+json jsonld;
        application/n-triples nt;
    }}

    location = / {{
        if ($ontoreview_target != "") {{
            return 303 $ontoreview_target;
        }}
        try_files /index.html =404;
    }}

    location / {{
        try_files $uri $uri/ =404;
    }}

    location ~ ^/(deploy/|Dockerfile|docker-compose\\.yml|DEPLOY\\.md) {{
        return 404;
    }}
}}
"""


DOCKERFILE = """# Generated by OntoReview: a small web server image with this documentation.
#   docker build -t ontology-docs . && docker run --rm -p 8080:80 ontology-docs
FROM nginx:1.27-alpine
COPY . /usr/share/nginx/html
RUN mv /usr/share/nginx/html/deploy/nginx.conf /etc/nginx/conf.d/default.conf \\
 && rm -rf /usr/share/nginx/html/deploy /usr/share/nginx/html/DEPLOY.md
EXPOSE 80
"""

COMPOSE = """# Generated by OntoReview:  docker compose up -d   then open http://localhost:8080/
services:
  docs:
    build: .
    ports:
      - "8080:80"
    restart: unless-stopped
"""

DOCKERIGNORE = """.git
.github
Dockerfile
docker-compose.yml
.dockerignore
"""

SERVE_SH = """#!/bin/sh
# Generated by OntoReview: preview this documentation at http://localhost:8000/ (needs Python 3).
cd "$(dirname "$0")/.." && exec python3 -m http.server "${1:-8000}"
"""

SERVE_BAT = """@echo off
rem Generated by OntoReview: preview this documentation at http://localhost:8000/ (needs Python 3).
cd /d "%~dp0.."
python -m http.server %1
"""


def deploy_readme(title: str, files: list[dict], base_url: str | None, branch: str = "main",
                  conneg: bool = True) -> str:
    name = title or "this ontology"
    dl = ", ".join(f"`{f['file']}`" for f in files) or "the serializations"
    w3id = ("\n- `w3id.htaccess`: the redirect rules to submit to "
            "[perma-id/w3id.org](https://github.com/perma-id/w3id.org) for a permanent IRI.") if base_url else ""
    conneg_txt = (f"\n\nAll servers below can do **content negotiation** on the site root: a client that asks for "
                  f"RDF (e.g. `curl -H 'Accept: text/turtle' <url>/`) gets {dl}; browsers get the HTML. GitHub "
                  "Pages cannot (it serves files only); everything else on the site works there."
                  if conneg and files else "")
    return f"""# Deploying the documentation of {name}

This folder is a complete static website, generated by [OntoReview](https://github.com/CAIRNepal/ontoreview).
It needs no build step and no database: copy it to any web server. `standalone.html` is the same
documentation in one file, for sharing by e-mail or opening offline.{conneg_txt}

## Quick look on your computer

- Open `index.html` (or `standalone.html`) in a browser, or
- `sh deploy/serve.sh` (Windows: `deploy\\serve.bat`), then open http://localhost:8000/
  (any static server works, e.g. `python3 -m http.server`).

## GitHub Pages (automatic, free)

The workflow `{PAGES_WORKFLOW}` publishes this folder on every push to `{branch}`.

1. Create an empty repository on GitHub.
2. Push this folder to it:
   ```sh
   git init -b {branch}
   git add -A && git commit -m "Ontology documentation"
   git remote add origin https://github.com/<you>/<repo>.git
   git push -u origin {branch}
   ```
3. In the repository: **Settings > Pages > Build and deployment > Source: GitHub Actions** (once).
4. The site appears at `https://<you>.github.io/<repo>/` (Actions tab shows progress).

The OntoReview app does steps 2 and 3 for you: **Deploy to GitHub Pages** on a website result or in
Run history. Later builds push to the same repository, so the site updates with each deploy.

To rebuild the docs from the ontology in CI instead (e.g. in the ontology's own repository), use a
workflow that runs OntoReview first:

```yaml
      - uses: actions/setup-python@v5
        with: {{python-version: "3.12"}}
      - run: pip install ontoreview && ontoreview build my-ontology.ttl -o site --no-oops
      - uses: actions/upload-pages-artifact@v3
        with: {{path: site}}
```

## Docker

```sh
docker compose up -d            # http://localhost:8080/
# or
docker build -t ontology-docs . && docker run --rm -p 8080:80 ontology-docs
```

The image is nginx with `deploy/nginx.conf` (content negotiation included). Put it behind your
usual reverse proxy / TLS.

## Without Docker

- **nginx:** copy the folder to the web root and `deploy/nginx.conf` to `/etc/nginx/conf.d/`
  (adjust `root` and `server_name`), then `nginx -s reload`.
- **Apache:** copy the folder; the `.htaccess` here sets the media types and content negotiation
  (needs `AllowOverride All` and `mod_rewrite`).
- **Any static host** (Netlify, Cloudflare Pages, S3, a university web space): upload the folder
  as is.{w3id}

## What is in this folder

- `index.html` and the pages, `assets/`, `ontoreview-data.js`: the website.
- {dl}: the ontology for download.
- `quality.json`, `cdi.json`, `si.json`, `iri-checks.json`, `provenance.ttl`: the quality report and
  what each check was verified against, with times and releases (when the checks ran).
- `llms.txt`, `llms-full.txt`, `*.md`, `ontology.json`: versions for language models and tools.
- `Dockerfile`, `docker-compose.yml`, `deploy/`, `{PAGES_WORKFLOW}`, this file: deployment only;
  safe to delete if you do not use them.
"""


def write_deploy_files(out_dir: Path, title: str, files: list[dict], base_url: str | None = None,
                       branch: str = "main", conneg: bool = True) -> list[Path]:
    """Write the deployment kit into a website folder. Returns the files written."""
    content = {
        "DEPLOY.md": deploy_readme(title, files, base_url, branch, conneg),
        "Dockerfile": DOCKERFILE,
        "docker-compose.yml": COMPOSE,
        ".dockerignore": DOCKERIGNORE,
        "deploy/nginx.conf": nginx_server(files if conneg else []),
        "deploy/serve.sh": SERVE_SH,
        "deploy/serve.bat": SERVE_BAT,
        PAGES_WORKFLOW: pages_workflow(branch),
    }
    out = []
    for rel, text in content.items():
        path = out_dir / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, "utf-8", newline="\r\n" if rel.endswith(".bat") else None)
        if rel.endswith(".sh"):
            path.chmod(0o755)
        out.append(path)
    return out


