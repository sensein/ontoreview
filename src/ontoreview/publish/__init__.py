"""Publishing artefacts: serializations, content negotiation, citation and provenance files."""

from __future__ import annotations

import datetime as _dt
import re
from pathlib import Path

from rdflib import Graph, Literal, Namespace, URIRef
from rdflib.namespace import DCTERMS, PROV, RDF, XSD

from ..model.entities import Metadata, Ontology

SERIALIZATIONS = {
    # key: (extension, rdflib format, media type, label)
    "ttl": ("ttl", "turtle", "text/turtle", "Turtle"),
    "owl": ("owl", "xml", "application/rdf+xml", "RDF/XML"),
    "rdf": ("rdf", "xml", "application/rdf+xml", "RDF/XML"),
    "jsonld": ("jsonld", "json-ld", "application/ld+json", "JSON-LD"),
    "nt": ("nt", "nt", "application/n-triples", "N-Triples"),
    "n3": ("n3", "n3", "text/n3", "Notation3"),
    "trig": ("trig", "trig", "application/trig", "TriG"),
}


def write_serializations(graph: Graph, out: Path, basename: str, keys: list[str]) -> list[dict]:
    files = []
    for key in keys:
        if key not in SERIALIZATIONS:
            continue
        ext, fmt, media, label = SERIALIZATIONS[key]
        path = out / f"{basename}.{ext}"
        graph.serialize(destination=str(path), format=fmt, encoding="utf-8")
        files.append({"key": key, "file": path.name, "media": media, "label": label,
                      "size": path.stat().st_size, "path": str(path)})
    return files


def htaccess(files: list[dict], rewrite_base: str = "/") -> str:
    lines = [
        "# Generated by ontoreview: content negotiation for the ontology documentation.",
        "# Place this file in the directory that serves the ontology IRI.",
        "AddType text/turtle .ttl",
        "AddType application/rdf+xml .owl .rdf",
        "AddType application/ld+json .jsonld",
        "AddType application/n-triples .nt",
        "AddType text/n3 .n3",
        "AddType application/trig .trig",
        "AddCharset UTF-8 .ttl .jsonld .nt .n3 .trig .html",
        "",
        "Options -MultiViews",
        "RewriteEngine on",
        f"RewriteBase {rewrite_base}",
        "",
    ]
    for f in files:
        media = f["media"]
        mt = media.replace("+", "\\+").replace(".", "\\.")
        lines += [
            f"# {f['label']}",
            f"RewriteCond %{{HTTP_ACCEPT}} {mt}",
            f"RewriteRule ^$ {f['file']} [R=303,L]",
            "",
        ]
    lines += [
        "# Default: HTML documentation",
        "RewriteCond %{HTTP_ACCEPT} text/html [OR]",
        "RewriteCond %{HTTP_ACCEPT} application/xhtml\\+xml [OR]",
        "RewriteCond %{HTTP_USER_AGENT} ^Mozilla/.*",
        "RewriteRule ^$ index.html [R=303,L]",
        "",
        "# Hash-less term IRIs (slash namespaces) redirect to their anchor in the docs",
        "RewriteCond %{REQUEST_FILENAME} !-f",
        "RewriteCond %{REQUEST_FILENAME} !-d",
        "RewriteRule ^([A-Za-z0-9_\\-.]+)$ index.html#$1 [R=303,NE,L]",
        "",
    ]
    return "\n".join(lines)


def nginx_conf(files: list[dict], location: str = "/") -> str:
    entries = []
    for f in files:
        media = f["media"].replace("+", "\\+")
        entries.append(f'    "~{media}" /{f["file"]};')
    mapping = "\n".join(entries)
    return f"""# Generated by ontoreview. Include in your nginx `http {{}}` block.
map $http_accept $ontoreview_target {{
    default /index.html;
{mapping}
}}

server {{
    # ... your listen / server_name directives ...
    location = {location} {{
        return 303 $ontoreview_target;
    }}
    location {location} {{
        types {{
            text/turtle ttl;
            application/rdf+xml owl rdf;
            application/ld+json jsonld;
            application/n-triples nt;
        }}
        try_files $uri $uri/ =404;
    }}
}}
"""


def w3id_htaccess(target_url: str, files: list[dict]) -> str:
    target = target_url.rstrip("/") + "/"
    rules = []
    for f in files:
        mt = f["media"].replace("+", "\\+")
        rules.append(f"RewriteCond %{{HTTP_ACCEPT}} {mt}\nRewriteRule ^$ {target}{f['file']} [R=303,L]")
    body = "\n\n".join(rules)
    return f"""# Generated by ontoreview: submit to https://github.com/perma-id/w3id.org
Options +FollowSymLinks
RewriteEngine on

{body}

RewriteRule ^$ {target} [R=303,L]
RewriteRule ^(.+)$ {target}index.html#$1 [R=303,NE,L]
"""


def _year(m: Metadata) -> str:
    for d in (m.issued, m.modified, m.created):
        if d:
            mm = re.search(r"(\d{4})", d)
            if mm:
                return mm.group(1)
    return str(_dt.date.today().year)


def citation_text(m: Metadata, url: str | None) -> str:
    if m.citation:
        return m.citation
    authors = ", ".join(a.name for a in m.creators) or "Anonymous"
    parts = [f"{authors} ({_year(m)}).", f"{m.title or 'Untitled ontology'}."]
    if m.version_info:
        parts.append(f"Version {m.version_info}.")
    if m.publishers:
        parts.append(f"{', '.join(a.name for a in m.publishers)}.")
    link = m.doi or m.iri or url
    if link:
        parts.append(link)
    return " ".join(parts)


def bibtex(m: Metadata, url: str | None) -> str:
    key = re.sub(r"[^A-Za-z0-9]", "", (m.preferred_prefix or m.title or "ontology"))[:30] + _year(m)
    fields = {
        "title": m.title,
        "author": " and ".join(a.name for a in m.creators) or None,
        "year": _year(m),
        "version": m.version_info,
        "url": m.iri or url,
        "doi": (m.doi or "").replace("https://doi.org/", "") or None,
        "publisher": ", ".join(a.name for a in m.publishers) or None,
        "note": "Ontology",
    }
    body = ",\n".join(f"  {k} = {{{v}}}" for k, v in fields.items() if v)
    return f"@misc{{{key},\n{body}\n}}"


def citation_cff(m: Metadata, url: str | None) -> str:
    def esc(s: str) -> str:
        return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

    lines = [
        "cff-version: 1.2.0",
        'message: "If you use this ontology, please cite it as below."',
        "type: dataset",
        f"title: {esc(m.title or 'Untitled ontology')}",
    ]
    if m.version_info:
        lines.append(f"version: {esc(m.version_info)}")
    if m.doi:
        lines.append(f"doi: {esc(m.doi.replace('https://doi.org/', ''))}")
    if m.iri or url:
        lines.append(f"url: {esc(m.iri or url)}")
    if m.license_label and re.match(r"^[A-Za-z0-9.\-]+$", (m.license or "").rsplit("/", 1)[-1]):
        pass
    if m.modified or m.issued:
        d = re.search(r"\d{4}-\d{2}-\d{2}", m.modified or m.issued or "")
        if d:
            lines.append(f"date-released: {d.group(0)}")
    lines.append("authors:")
    if not m.creators:
        lines.append("  - name: Anonymous")
    for a in m.creators:
        parts = a.name.rsplit(" ", 1)
        if len(parts) == 2:
            lines.append(f"  - given-names: {esc(parts[0])}\n    family-names: {esc(parts[1])}")
        else:
            lines.append(f"  - name: {esc(a.name)}")
        if a.orcid:
            lines.append(f"    orcid: {esc(a.orcid)}")
        if a.affiliation:
            lines.append(f"    affiliation: {esc(a.affiliation)}")
    if m.keywords:
        lines.append("keywords:")
        lines += [f"  - {esc(k)}" for k in m.keywords]
    return "\n".join(lines) + "\n"


def _when(value: str | None) -> tuple[_dt.datetime, bool] | None:
    """A metadata date or timestamp as an aware UTC datetime, plus whether it was a date only.
    None for free text that is not a date."""
    if not value:
        return None
    v = str(value).strip()
    try:
        d = _dt.datetime.fromisoformat(v.replace("Z", "+00:00"))
    except ValueError:
        m = re.match(r"(\d{4})-(\d{2})-(\d{2})", v) or re.fullmatch(r"(\d{4})", v)
        if not m:
            return None
        parts = [int(x) for x in m.groups()] + [1, 1]
        try:
            return _dt.datetime(parts[0], parts[1], parts[2], tzinfo=_dt.timezone.utc), True
        except ValueError:
            return None
    date_only = "T" not in v and " " not in v.strip()
    return (d if d.tzinfo else d.replace(tzinfo=_dt.timezone.utc)).astimezone(_dt.timezone.utc), date_only


def _iso(d: _dt.datetime) -> str:
    return d.astimezone(_dt.timezone.utc).isoformat(timespec="seconds")


def provenance_record(onto: Ontology, source: str | Path, tool_version: str, started: _dt.datetime,
                      report=None, generated: _dt.datetime | None = None) -> dict:
    """What this documentation was made from, by what, and when: one record shown in the docs'
    Provenance section and written as ``provenance.ttl``, so both carry the same timestamps."""
    import hashlib

    m = onto.metadata
    generated = generated or _dt.datetime.now(_dt.timezone.utc)
    src = Path(str(source)) if source and not str(source).startswith(("http://", "https://")) else None
    sha = size = None
    if src is not None and src.is_file():
        sha, size = hashlib.sha256(src.read_bytes()).hexdigest(), src.stat().st_size
    events: list[dict] = []

    def event(when, title: str, detail: str = "", kind: str = "ontology") -> None:
        w = _when(when) if not isinstance(when, _dt.datetime) else (when, False)
        if w:
            events.append({"when": _iso(w[0]), "date_only": w[1], "title": title, "detail": detail, "kind": kind})

    version = f" {m.version_info}" if m.version_info else ""
    event(m.created, "Ontology created")
    event(m.issued, f"Version{version} published" if version else "Version published")
    event(m.modified, "Ontology last modified")
    checks = []
    for ext in (report.external if report else []):
        if ext.error:
            continue
        checks.append(ext.tool)
        pv = ext.provenance or {}
        if pv.get("checked_at"):
            n = len(pv.get("releases") or [])
            summ = pv.get("summary") or {}
            detail = f"Verified against {n} reference release{'s' if n != 1 else ''}" if n else ""
            if summ.get("cdi") is not None:
                detail = f"CDI {summ['cdi']:.2f}" + (f"; {detail.lower()}" if detail else "")
            if summ.get("si") is not None and summ.get("taxonomy_size"):
                detail = f"SI {summ['si']} of {summ['taxonomy_size'] - 1} scientific domains"
            event(pv["checked_at"], f"{ext.tool} run", detail, "check")
    if report is not None:
        checks.insert(0, "OntoReview checks")
    name = src.name if src else str(source or "")
    fixes = None
    if src is not None:                 # a fixed version (a-v1.ttl) carries the record of its fixes
        from ..fixes.session import fixes_record
        rec = fixes_record(src)
        if rec and rec.get("output", {}).get("sha256") in (None, sha):    # only if the file is unchanged
            applied = rec.get("applied", [])
            kinds = {}
            for a in applied:
                kinds[a.get("source", a.get("kind"))] = kinds.get(a.get("source", a.get("kind")), 0) + 1
            fixes = {"derived_from": rec.get("source", {}), "created_at": rec.get("created_at"),
                     "applied": applied, "not_applied": len(rec.get("not_applied", [])),
                     "checks": rec.get("checks", {}), "kinds": kinds}
            n_ai = sum(1 for a in applied if a.get("ai_assisted"))
            fixes["ai_assisted"] = n_ai
            event(rec.get("created_at"), f"{len(applied)} fix{'es' if len(applied) != 1 else ''} applied",
                  f"From {rec.get('source', {}).get('name', 'the original')}: "
                  + ", ".join(f"{n} {k.lower()}" for k, n in kinds.items())
                  + (f" · {n_ai} AI-assisted" if n_ai else ""), "fix")
    event(started, "Documentation build started", f"From {name}" if name else "", "build")
    event(generated, "Documentation generated",
          f"OntoReview {tool_version}" + (f"; checks: {', '.join(checks)}" if checks else ""), "build")
    events.sort(key=lambda e: e["when"])
    return {"ontology": {"iri": m.iri, "version_iri": m.version_iri, "version_info": m.version_info,
                         "prior_version": m.prior_version, "title": m.title},
            "source": {"name": name, "location": str(source or ""), "sha256": sha, "size": size},
            "tool": {"name": "OntoReview", "version": tool_version},
            "started": _iso(started), "generated": _iso(generated),
            "seconds": round((generated - started).total_seconds(), 1),
            "checks": checks, "events": events, "fixes": fixes}


def provenance_graph(onto: Ontology, source: str, tool_version: str, record: dict | None = None) -> Graph:
    """A PROV-O description of the ontology version and of this documentation build. With
    ``record`` (from :func:`provenance_record`) the build's times and source checksum match what
    the docs show."""
    m = onto.metadata
    g = Graph()
    g.bind("prov", PROV)
    g.bind("dcterms", DCTERMS)
    ontoreview = Namespace("https://w3id.org/ontoreview#")
    entity = URIRef(m.version_iri or m.iri or "urn:ontoreview:ontology")
    g.add((entity, RDF.type, PROV.Entity))
    if m.title:
        g.add((entity, DCTERMS.title, Literal(m.title)))
    if m.prior_version:
        g.add((entity, PROV.wasRevisionOf, URIRef(m.prior_version)))
    for a in m.creators:
        agent = URIRef(a.iri) if a.iri else None
        if agent is None:
            continue
        g.add((agent, RDF.type, PROV.Agent))
        g.add((entity, PROV.wasAttributedTo, agent))
    for a in m.contributors:
        if a.iri:
            g.add((entity, PROV.wasAttributedTo, URIRef(a.iri)))
    for d, pred in ((m.issued, PROV.generatedAtTime), (m.modified, DCTERMS.modified)):
        if d:
            g.add((entity, pred, Literal(d)))
    doc = URIRef("urn:ontoreview:documentation")
    act = URIRef("urn:ontoreview:build")
    g.add((doc, RDF.type, PROV.Entity))
    g.add((doc, PROV.wasDerivedFrom, entity))
    g.add((doc, PROV.wasGeneratedBy, act))
    g.add((act, RDF.type, PROV.Activity))
    g.add((act, PROV.used, Literal(source)))
    rec = record or {}
    ended = rec.get("generated") or _dt.datetime.now(_dt.timezone.utc).isoformat(timespec="seconds")
    if rec.get("started"):
        g.add((act, PROV.startedAtTime, Literal(rec["started"], datatype=XSD.dateTime)))
    g.add((act, PROV.endedAtTime, Literal(ended, datatype=XSD.dateTime)))
    g.add((doc, PROV.generatedAtTime, Literal(ended, datatype=XSD.dateTime)))
    sha = (rec.get("source") or {}).get("sha256")
    if sha:
        src = URIRef(f"urn:sha256:{sha}")
        g.add((src, RDF.type, PROV.Entity))
        g.add((src, DCTERMS.identifier, Literal(f"sha256:{sha}")))
        g.add((src, DCTERMS.title, Literal(source)))
        g.add((act, PROV.used, src))
    g.add((act, PROV.wasAssociatedWith, ontoreview[f"v{tool_version}"]))
    fixes = rec.get("fixes") if rec else None
    if fixes and sha:
        _fix_provenance(g, fixes, URIRef(f"urn:sha256:{sha}"))
    return g


def _fix_provenance(g: Graph, fixes: dict, fixed: URIRef) -> None:
    """The fixed file was derived from the original by an apply-fixes activity; each accepted fix is
    an activity associated with the rule or the model (with its revision) that produced it."""
    from rdflib.namespace import RDFS

    orig = fixes.get("derived_from") or {}
    if orig.get("sha256"):
        src = URIRef(f"urn:sha256:{orig['sha256']}")
        g.add((src, RDF.type, PROV.Entity))
        g.add((src, DCTERMS.title, Literal(orig.get("name", ""))))
        g.add((fixed, PROV.wasDerivedFrom, src))
    apply = URIRef("urn:ontoreview:apply-fixes")
    g.add((apply, RDF.type, PROV.Activity))
    g.add((apply, RDFS.label, Literal(f"{len(fixes.get('applied', []))} fixes applied")))
    if orig.get("sha256"):
        g.add((apply, PROV.used, URIRef(f"urn:sha256:{orig['sha256']}")))
    g.add((fixed, PROV.wasGeneratedBy, apply))
    if fixes.get("created_at"):
        g.add((apply, PROV.endedAtTime, Literal(fixes["created_at"], datatype=XSD.dateTime)))
    for a in fixes.get("applied", []):
        node = URIRef(f"urn:ontoreview:fix:{a['id']}")
        g.add((node, RDF.type, PROV.Activity))
        g.add((node, DCTERMS.isPartOf, apply))
        g.add((node, RDFS.label, Literal(f"{a.get('title', '')}: {a.get('option', '')}")))
        g.add((node, DCTERMS.description, Literal(f"{a.get('rule')} on {a.get('subject') or 'the ontology'}; "
                                                  f"{len(a.get('add', []))} added, {len(a.get('remove', []))} removed"
                                                  + ("; edited by the user" if a.get("edited") else ""))))
        if a.get("accepted_at"):
            g.add((node, PROV.endedAtTime, Literal(a["accepted_at"], datatype=XSD.dateTime)))
        mb = a.get("made_by") or {}
        if mb.get("type") == "llm":
            g.add((node, DCTERMS.type, Literal("AI-assisted")))
            agent = URIRef("urn:ontoreview:model:" + "/".join(str(mb.get(k, "")) for k in ("source", "model"))
                           .replace(" ", "_") + (f"@{mb['revision']}" if mb.get("revision") else ""))
            g.add((agent, RDF.type, PROV.SoftwareAgent))
            g.add((agent, RDFS.label, Literal(f"{mb.get('provider', mb.get('source'))} · {mb.get('model')}"
                                              + (f" ({mb['revision']})" if mb.get("revision") else ""))))
        else:
            agent = URIRef(f"urn:ontoreview:fixer:{mb.get('id', a.get('rule', 'rule'))}")
            g.add((agent, RDF.type, PROV.SoftwareAgent))
        g.add((node, PROV.wasAssociatedWith, agent))
